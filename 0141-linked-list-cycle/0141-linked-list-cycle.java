/**
 * Definition for singly-linked list.
 * class ListNode {
 *     int val;
 *     ListNode next;
 *     ListNode(int x) {
 *         val = x;
 *         next = null;
 *     }
 * }
 */
public class Solution {
    public boolean hasCycle(ListNode head) {
        Set<ListNode> v = new HashSet<>();
        ListNode curr = head;
        while (curr != null) {
            if (v.contains(curr)) return true;
            v.add(curr);
            curr = curr.next;
        }
        return false;
    }
}

